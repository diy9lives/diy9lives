#!/usr/bin/env python3
"""Automated checks for DIY9lives. Run with a local server on port 8765."""
import os, re, glob, html, urllib.request, json, sys, math
from PIL import Image
from playwright.sync_api import sync_playwright

BASE = os.environ.get("BASE_URL", "http://127.0.0.1:8765")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
results = []
def check(name, ok, detail=""):
    results.append((name, bool(ok), detail))
    print(("PASS " if ok else "FAIL ") + name + ((" — " + detail) if detail else ""))

# 1. HTTP + links + images
pages = sorted(glob.glob("*.html") + glob.glob("guides/*.html"))
bad_pages, bad_links, bad_imgs, dim_mismatch = [], [], [], []
for f in pages:
    try:
        r = urllib.request.urlopen(BASE + "/" + f, timeout=5)
        if r.status != 200: bad_pages.append((f, r.status))
    except Exception as e:
        bad_pages.append((f, str(e)))
    t = open(f).read()
    for href in re.findall(r'(?:href|src)="([^"]+)"', t):
        if href.startswith(("#", "http", "mailto:", "tel:", "data:", "javascript:")): continue
        p = href.lstrip("/").split("#")[0].split("?")[0]
        if p and not os.path.exists(p):
            (bad_imgs if re.search(r"\.(webp|png|jpg|jpeg|gif|svg|ico)$", p) else bad_links).append((f, href))
    for m in re.finditer(r'<img\b[^>]*>', t):
        tag = m.group(0)
        src = re.search(r'src="([^"]+)"', tag)
        w = re.search(r'width="(\d+)"', tag); h = re.search(r'height="(\d+)"', tag)
        if src and w and h and os.path.exists(src.group(1).lstrip("/")):
            iw, ih = Image.open(src.group(1).lstrip("/")).size
            if (iw, ih) != (int(w.group(1)), int(h.group(1))):
                dim_mismatch.append((f, src.group(1), (iw, ih), (w.group(1), h.group(1))))
check("every HTML page returns 200", not bad_pages, str(bad_pages[:3]))
check("zero broken internal links", not bad_links, str(bad_links[:3]))
check("zero missing image assets", not bad_imgs, str(bad_imgs[:3]))
check("image width/height match files", not dim_mismatch, str(dim_mismatch[:3]))

# 2. Sitemap
import xml.etree.ElementTree as ET
sx = ET.parse("sitemap.xml").getroot()
ns = {"s": "http://www.sitemaps.org/schemas/sitemap/0.9"}
locs = [e.text for e in sx.findall("s:url/s:loc", ns)]
lastmods = [e.text for e in sx.findall("s:url/s:lastmod", ns)]
indexable = [f for f in pages if 'name="robots" content="noindex' not in open(f).read()]
expected = set("https://www.diy9lives.com/" + ("" if f == "index.html" else f) for f in indexable)
check("sitemap is valid XML and complete", set(locs) == expected, f"{len(locs)} URLs, {len(expected)} indexable")
check("sitemap excludes noindex pages", not any(('name="robots" content="noindex' in open(f).read()) and ("https://www.diy9lives.com/" + f in locs) for f in pages))
check("sitemap lastmod is 2026-11-09", all(x == "2026-11-09" for x in lastmods), f"{len(lastmods)} dates")

# 3. Forbidden words
forbidden = re.compile(r"\b(AI|ChatGPT|GPT|LLM)\b|artificial intelligence|generated by", re.I)
hits = []
for f in pages:
    t = open(f).read()
    t = re.sub(r"(?is)<(script|style)[^>]*>.*?</\1>", " ", t)
    v = html.unescape(re.sub(r"(?s)<[^>]+>", " ", t))
    for m in forbidden.finditer(v):
        hits.append((f, v[max(0, m.start()-40):m.end()+40].replace("\n", " ")))
check("forbidden words in visible text = 0", not hits, str(hits[:2]))

# 4. Every calculator loads without JS page errors
not_tools = {"index.html","about.html","contact.html","privacy.html","terms.html","disclaimer.html","editorial.html",
             "money-tools.html","car-tools.html","home-tools.html","kitchen-tools.html"}
tools = [f for f in sorted(glob.glob("*.html")) if f not in not_tools and not f.startswith("guides/")]
js_errors = []
with sync_playwright() as p:
    browser = p.chromium.launch(channel="chrome", args=["--no-sandbox"])
    page = browser.new_page(viewport={"width": 1280, "height": 900})
    page.set_default_timeout(6000)
    page.route("**/*", lambda r: r.abort() if any(d in r.request.url for d in
               ("googletagmanager","googlesyndication","google-analytics","doubleclick")) else r.continue_())
    errs = []
    page.on("pageerror", lambda e: errs.append(str(e)))
    for f in tools:
        errs.clear()
        try:
            page.goto(f"{BASE}/{f}", wait_until="domcontentloaded", timeout=12000)
            page.wait_for_timeout(80)
        except Exception as e:
            errs.append("navigation: " + str(e))
        if errs:
            js_errors.append((f, list(errs[:2])))
    check("all 70 tool pages run with no JS page errors", not js_errors, f"{len(tools)} tools; {str(js_errors[:2])}")

    # 5. Independent output checks (fresh page, no request interception)
    page.close()
    page = browser.new_page(viewport={"width": 1280, "height": 900})
    page.set_default_timeout(6000)
    checks = [
        ("mortgage-calculator", "#mPayment", "$2,255", "280000 at 7%/360 + escrow"),
        ("loan-calculator", "#lPayment", "$332", "10000 at 12%/36"),
        ("car-payment-calculator", "#cPayment", "$634", "35000+6% tax-5000 at 6.9%/60"),
        ("home-affordability-calculator", "#homePrice", "$300,242", "28/36 DTI solve"),
        ("retirement-calculator", "#fvNominal", "$1,130,650", "monthly FV, 7%"),
        ("paint-calculator", "#totalGal", "2", "346 sq ft x2 coats /400 +10%"),
        ("concrete-calculator", "#cyVal", "1.36", "100 sq ft x4/12 x1.1 /27"),
        ("flooring-calculator", "#boxVal", "15", "(224+48)x1.1/20"),
        ("mulch-soil-gravel-calculator", "#cyVal", "1.56", "160 sq ft x3/12 x1.05 /27"),
        ("btu-calculator", "#sizeVal", "8,000", "350 sq ft ladder"),
        ("tip-calculator", "#tipAmt", "$11.70", "65 x 18%"),
        ("percentage-calculator", "#res1", "30", "15% of 200"),
        ("cooking-measurement-converter", "#resultVal", "120", "1 cup flour reference"),
        ("compound-interest", "#iResult", "$44,665", "5000+200/mo, 7%, 120 mo"),
        ("out-the-door-price-calculator", "#totalVal", "$34,590", "32000x1.0575+750"),
        ("tire-size-calculator", "#stockStats", "26.63", "225/60R16 diameter"),
        ("student-loan-calculator", "#compareGrid", "112 months", "log payoff, 30000/6%/350"),
        ("unit-price-comparator", "#prod2", "0.2809", "8.99/32"),
        ("debt-payoff-planner", "#compareGrid", "55 months", "monthly simulation"),
        ("rent-vs-buy-calculator", "#winnerVal", "Buying", "7-year net cost"),
        ("salary-calculator", "#thPay", "$3,665", "withholding estimate"),
    ]
    wrong = []
    for f, sel, exp, why in checks:
        print("  checking", f, flush=True)
        page.goto(f"{BASE}/{f}.html", wait_until="domcontentloaded"); page.wait_for_timeout(120)
        try:
            got = page.locator(sel).first.inner_text()
        except Exception as e:
            wrong.append((f, "missing " + sel)); continue
        if exp.lower() not in got.lower():
            wrong.append((f, exp, got[:80]))
    check(f"calculator outputs match {len(checks)} independent checks", not wrong, str(wrong[:4]))

    # 6. Tire share link
    page.goto(f"{BASE}/tire-size-calculator.html?w=205&a=55&r=16&cw=225&ca=45&cr=17", wait_until="domcontentloaded")
    page.wait_for_timeout(250)
    vals = (page.locator("#inWidth").input_value(), page.locator("#inAspect").input_value(),
            page.locator("#inRim").input_value(), page.locator("#cmpWidth").input_value())
    title = page.locator("#detailTitle").inner_text()
    check("tire share link restores stock and comparison", vals == ("205","55","16","225") and "225/45R17" in title, f"{vals} {title}")
    check("tire presets, share and print controls exist",
          page.locator(".preset").count() >= 5 and page.locator("#shareBtn").count() == 1 and page.locator("#printBtn").count() == 1)
    browser.close()

# 7. Screenshots
shots = sorted(glob.glob("img/screens/*.webp"))
heavy = [(s, round(os.path.getsize(s)/1024)) for s in shots if os.path.getsize(s) > 130*1024]
check("22 tool screenshots present", len(shots) == 22, f"{len(shots)} files")
check("screenshots are reasonably compressed", not heavy, str(heavy))

fails = [r for r in results if not r[1]]
print("\nSUMMARY", len(results)-len(fails), "passed,", len(fails), "failed")
sys.exit(1 if fails else 0)
